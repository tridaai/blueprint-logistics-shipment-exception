"""Retrieval relevance eval — the labelled query→policy set.

Pins the harness in evals/run_retrieval_evals.py: the golden cases
load, both rankings (keyword, and hybrid over the labelled stand-in
embedder) clear the recall gate, and the customer-SOP case ranks the
customer's own policy first. The full report is regenerated by
``make retrieval-evals``; this test keeps the gate inside the suite.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parents[1] / "evals"


def _load_runner():
    spec = importlib.util.spec_from_file_location(
        "run_retrieval_evals", EVALS_DIR / "run_retrieval_evals.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cases() -> list[dict]:
    return [
        json.loads(line)
        for line in (EVALS_DIR / "retrieval_golden.jsonl")
        .read_text(encoding="utf-8")
        .splitlines()
        if line.strip()
    ]


def test_golden_set_is_labelled_and_grounded():
    cases = _cases()
    assert len(cases) >= 40
    from shipment_agent.policies_data import POLICIES

    known = {p["policy_id"] for p in POLICIES} | {
        "POL-OPS-77",
        "SOP-ACME-01",
        "SOP-GLOBEX-01",
    }
    known |= {
        case["document"]["policy_id"]
        for case in cases
        if case.get("corpus") == "stored"
    }
    for case in cases:
        assert case["query"].strip()
        # A case pins expected hits, forbidden hits, or both (a
        # forbidden-only case scores on absence — see the runner).
        assert case["expected"] or case.get("forbidden"), case["case_id"]
        assert set(case["expected"]) <= known, case["case_id"]
        assert set(case.get("forbidden", [])) <= known, case["case_id"]
        assert case.get("corpus", "standard") in (
            "standard",
            "ops_sop",
            "tenant_acme",
            "tenant_globex",
            "stored",
        ), case["case_id"]
        if case.get("corpus") == "stored":
            assert case["tenant"] and case["document"]["text"], case["case_id"]


def test_both_rankings_clear_the_recall_gate():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    assert report["passed"] is True
    keyword = report["summary"]["keyword"]
    assert keyword["mean_recall_at_3"] >= runner.KEYWORD_THRESHOLD
    hybrid_name = next(name for name in report["summary"] if name.startswith("hybrid"))
    # The stand-in hybrid is plumbing evidence (the merge works over
    # the labelled set), labelled as such in the report framing.
    assert report["summary"][hybrid_name]["mean_recall_at_3"] >= 0.9
    assert "stand-in" in report["embeddings"]


def test_hybrid_carries_the_denial_cases_and_holds_the_floor():
    """Round 10's polarity strike, measured on the labelled set.

    RQ-34 (the clean inspection: "no damage, no leak found") was
    the case the hybrid merge kept burying — the semantic half
    embedded the denials at full weight and the damage policy
    outranked the routine one. With denied signals struck before
    embedding, the routine policy reaches the fused top-3. The
    floor assertion is the regression guard the round-9 backlog
    asked for: the hybrid mean may not sit below the keyword mean
    on this set, so the merge cannot silently re-bury a case the
    keyword half already carries."""
    runner = _load_runner()
    report = runner.evaluate(_cases())
    hybrid_name = next(
        name for name in report["summary"] if name.startswith("hybrid")
    )
    rows = {r["case_id"]: r for r in report["cases"]}
    for case_id in ("RQ-17", "RQ-21", "RQ-34"):
        assert rows[case_id]["results"][hybrid_name]["recall_at_3"] == 1.0, case_id
    assert (
        report["summary"][hybrid_name]["mean_recall_at_3"]
        >= report["summary"]["keyword"]["mean_recall_at_3"]
    )


def test_customer_sop_case_ranks_the_sop_first():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    row = next(r for r in report["cases"] if r["case_id"] == "RQ-04")
    assert row["expected"] == ["POL-OPS-77"]
    for result in row["results"].values():
        assert result["retrieved"][0] == "POL-OPS-77"
        assert result["recall_at_3"] == 1.0


def test_tenant_sop_cases_rank_for_their_tenant_and_never_leak():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    rows = {r["case_id"]: r for r in report["cases"]}
    # Each tenant's SOP ranks in its own view…
    for case_id, sop in (("RQ-37", "SOP-ACME-01"), ("RQ-39", "SOP-GLOBEX-01")):
        for result in rows[case_id]["results"].values():
            assert result["hits"] == [sop], case_id
            assert result["recall_at_3"] == 1.0, case_id
    # …and the same query in the OTHER tenant's view surfaces
    # nothing of it: forbidden, absent, full score for the absence.
    for case_id, sop in (("RQ-38", "SOP-ACME-01"), ("RQ-40", "SOP-GLOBEX-01")):
        for result in rows[case_id]["results"].values():
            assert sop not in result["retrieved"], case_id
            assert result["forbidden_hits"] == [], case_id
            assert result["recall_at_3"] == 1.0, case_id


def test_stored_document_cases_hit_while_stored_and_vanish_after_delete():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    rows = {r["case_id"]: r for r in report["cases"]}
    for case_id in ("RQ-41", "RQ-42"):
        for result in rows[case_id]["results"].values():
            assert result["recall_at_3"] == 1.0, case_id
            assert result["after_delete_clear"] is True, case_id
