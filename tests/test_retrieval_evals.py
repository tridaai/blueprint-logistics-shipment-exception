"""Retrieval relevance eval — the labelled query→policy set.

Pins the harness in evals/run_retrieval_evals.py: the golden cases
load, both rankings (keyword, and hybrid over the labelled stand-in
embedder) clear the recall gate, and the customer-SOP case ranks the
customer's own policy first. The full report is regenerated by
``make retrieval-evals``; this test keeps the gate inside the suite.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parents[1] / "evals"


def _load_runner():
    spec = importlib.util.spec_from_file_location(
        "run_retrieval_evals", EVALS_DIR / "run_retrieval_evals.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cases() -> list[dict]:
    return [
        json.loads(line)
        for line in (EVALS_DIR / "retrieval_golden.jsonl")
        .read_text(encoding="utf-8")
        .splitlines()
        if line.strip()
    ]


def test_golden_set_is_labelled_and_grounded():
    cases = _cases()
    assert len(cases) >= 12
    from shipment_agent.policies_data import POLICIES

    known = {p["policy_id"] for p in POLICIES} | {"POL-OPS-77"}
    for case in cases:
        assert case["query"].strip()
        assert case["expected"], case["case_id"]
        assert set(case["expected"]) <= known, case["case_id"]
        assert case.get("corpus", "standard") in ("standard", "ops_sop")


def test_both_rankings_clear_the_recall_gate():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    assert report["passed"] is True
    keyword = report["summary"]["keyword"]
    assert keyword["mean_recall_at_3"] >= runner.KEYWORD_THRESHOLD
    hybrid_name = next(name for name in report["summary"] if name.startswith("hybrid"))
    # The stand-in hybrid is plumbing evidence (the merge works over
    # the labelled set), labelled as such in the report framing.
    assert report["summary"][hybrid_name]["mean_recall_at_3"] >= 0.9
    assert "stand-in" in report["embeddings"]


def test_customer_sop_case_ranks_the_sop_first():
    runner = _load_runner()
    report = runner.evaluate(_cases())
    row = next(r for r in report["cases"] if r["case_id"] == "RQ-04")
    assert row["expected"] == ["POL-OPS-77"]
    for result in row["results"].values():
        assert result["retrieved"][0] == "POL-OPS-77"
        assert result["recall_at_3"] == 1.0
